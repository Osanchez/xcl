#!/usr/bin/env bash
# Manage the reverse-engineering tool clones in tools/ and check the system tools.
# See README.md. Bash 3.2 compatible (macOS); works in Git Bash.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MANIFEST="$HERE/tools.tsv"
LOCK="$HERE/tools.lock"
TOOLS="$HERE/tools"
TAB="$(printf '\t')"

usage() {
  cat <<'USAGE'
Usage: update.sh [command] [options]

Commands:
  update [--only a,b]         clone missing tools, fast-forward the others (default)
  status [--only a,b] [--offline]
                              branch, HEAD, commits behind origin, dirty and pinned flags
  doctor                      check the system tools for this platform (installs nothing)
  pin <name> <sha>            check out <sha> (detached) and keep update away from it
  unpin <name>                clear the pin and check out the tracked branch again
  list                        print the manifest
  -h, --help                  this text

tools.tsv is the manifest; tools.lock records the commit of every clone after
update, pin and unpin.
USAGE
}

die() { echo "error: $*" >&2; exit 2; }

platform() {
  case "$(uname -s)" in
    Darwin) echo macos ;;
    MINGW*|MSYS*|CYGWIN*) echo windows ;;
    *) echo linux ;;
  esac
}

# Print "name<TAB>source<TAB>branch" for the git rows, optionally filtered by $ONLY.
git_rows() {
  local name kind source branch rest
  while IFS="$TAB" read -r name kind source branch rest; do
    case "$name" in ''|'#'*|name) continue ;; esac
    [ "$kind" = git ] || continue
    if [ -n "${ONLY:-}" ]; then
      case ",$ONLY," in *",$name,"*) ;; *) continue ;; esac
    fi
    printf '%s\t%s\t%s\n' "$name" "$source" "$branch"
  done < "$MANIFEST"
}

row_for() { # name -> "name<TAB>source<TAB>branch" or empty
  ONLY="" git_rows | awk -F'\t' -v n="$1" '$1==n {print; exit}'
}

check_only() { # fail on unknown names in $ONLY
  [ -n "${ONLY:-}" ] || return 0
  local n old_ifs="$IFS"
  IFS=,
  for n in $ONLY; do
    IFS="$old_ifs"
    [ -n "$(row_for "$n")" ] || die "unknown tool in --only: $n"
  done
  IFS="$old_ifs"
}

is_pinned() {
  [ -f "$LOCK" ] && awk -F'\t' -v n="$1" '$1==n && $3=="pinned" {f=1} END {exit !f}' "$LOCK"
}

is_dirty() { [ -n "$(git -C "$TOOLS/$1" status --porcelain 2>/dev/null)" ]; }

set_pinned() { # name flag(pinned|-)
  local tmp="$LOCK.tmp"
  [ -f "$LOCK" ] || : > "$LOCK"
  if awk -F'\t' -v n="$1" '$1==n {f=1} END {exit !f}' "$LOCK"; then
    awk -F'\t' -v OFS='\t' -v n="$1" -v f="$2" '$1==n {$3=f} {print}' "$LOCK" > "$tmp"
  else
    { cat "$LOCK"; printf '%s\t-\t%s\t-\n' "$1" "$2"; } > "$tmp"
  fi
  mv "$tmp" "$LOCK"
}

write_lock() {
  local tmp="$LOCK.tmp" name src br sha flag date
  {
    echo "# Generated by update.sh. name<TAB>commit<TAB>pinned|-<TAB>commit date (ISO). Do not edit."
    ONLY="" git_rows | while IFS="$TAB" read -r name src br; do
      [ -d "$TOOLS/$name/.git" ] || continue
      sha="$(git -C "$TOOLS/$name" rev-parse HEAD 2>/dev/null)" || continue
      date="$(git -C "$TOOLS/$name" log -1 --format=%cI HEAD 2>/dev/null || echo -)"
      flag=-
      if is_pinned "$name"; then flag=pinned; fi
      printf '%s\t%s\t%s\t%s\n' "$name" "$sha" "$flag" "$date"
    done | sort
  } > "$tmp"
  mv "$tmp" "$LOCK"
}

cmd_update() {
  local failed="" name src br old new n rc
  check_only
  mkdir -p "$TOOLS"
  while IFS="$TAB" read -r name src br; do
    rc=0
    if [ ! -d "$TOOLS/$name/.git" ]; then
      echo "$name: cloning ($br)"
      if git clone --recurse-submodules --branch "$br" "$src" "$TOOLS/$name" >/dev/null 2>&1; then
        echo "$name: cloned at $(git -C "$TOOLS/$name" rev-parse --short HEAD)"
      elif rm -rf "${TOOLS:?}/$name" && git clone --branch "$br" "$src" "$TOOLS/$name" >/dev/null 2>&1; then
        echo "$name: WARNING a submodule could not be fetched (missing upstream?); cloned without submodules at $(git -C "$TOOLS/$name" rev-parse --short HEAD)" >&2
      else
        echo "$name: CLONE FAILED ($src)" >&2
        rm -rf "${TOOLS:?}/$name"
        failed="$failed $name"
      fi
      continue
    fi
    if is_pinned "$name"; then
      echo "$name: pinned at $(git -C "$TOOLS/$name" rev-parse --short HEAD), skipped"
      continue
    fi
    if is_dirty "$name"; then
      echo "$name: WARNING local changes, skipped" >&2
      continue
    fi
    old="$(git -C "$TOOLS/$name" rev-parse HEAD)"
    (
      cd "$TOOLS/$name"
      git fetch --prune --quiet
      if [ "$(git rev-parse --abbrev-ref HEAD)" != "$br" ]; then git checkout --quiet "$br"; fi
      git pull --ff-only --quiet
      git submodule update --init --recursive --quiet || echo "$name: WARNING submodule update failed" >&2
    ) >/dev/null || rc=$?
    if [ "$rc" -ne 0 ]; then
      echo "$name: UPDATE FAILED" >&2
      failed="$failed $name"
      continue
    fi
    new="$(git -C "$TOOLS/$name" rev-parse HEAD)"
    if [ "$old" = "$new" ]; then
      echo "$name: up to date ($(git -C "$TOOLS/$name" rev-parse --short HEAD))"
    else
      n="$(git -C "$TOOLS/$name" rev-list --count "$old..$new")"
      echo "$name: $(git -C "$TOOLS/$name" rev-parse --short "$old")..$(git -C "$TOOLS/$name" rev-parse --short "$new") ($n commits)"
      git -C "$TOOLS/$name" log --format='    %h %s' "$old..$new" | head -n 10
    fi
  done < <(git_rows)
  write_lock
  if [ -n "$failed" ]; then
    echo "" >&2
    echo "Failed:$failed" >&2
    return 1
  fi
}

cmd_status() {
  local offline=0 name src br cur short behind dirty pin
  check_only
  [ "${OFFLINE:-0}" = 1 ] && offline=1
  printf '%-18s %-8s %-9s %-7s %-6s %s\n' NAME BRANCH HEAD BEHIND DIRTY PINNED
  while IFS="$TAB" read -r name src br; do
    if [ ! -d "$TOOLS/$name/.git" ]; then
      printf '%-18s %-8s %-9s %-7s %-6s %s\n' "$name" "$br" "(missing)" - - -
      continue
    fi
    [ "$offline" = 1 ] || git -C "$TOOLS/$name" fetch --prune --quiet >/dev/null 2>&1 || true
    cur="$(git -C "$TOOLS/$name" rev-parse --abbrev-ref HEAD)"
    short="$(git -C "$TOOLS/$name" rev-parse --short HEAD)"
    behind="$(git -C "$TOOLS/$name" rev-list --count "HEAD..origin/$br" 2>/dev/null || echo '?')"
    dirty=no; if is_dirty "$name"; then dirty=yes; fi
    pin=no; if is_pinned "$name"; then pin=yes; fi
    [ "$cur" = HEAD ] && cur="detached"
    printf '%-18s %-8s %-9s %-7s %-6s %s\n' "$name" "$cur" "$short" "$behind" "$dirty" "$pin"
  done < <(git_rows)
}

run_guarded() { # run a check command under a ~10s guard when a timeout tool exists
  local t=""
  if command -v timeout >/dev/null 2>&1; then t=timeout
  elif command -v gtimeout >/dev/null 2>&1; then t=gtimeout; fi
  if [ -n "$t" ]; then "$t" 10 bash -c "$1" 2>&1; else bash -c "$1" 2>&1; fi
}

cmd_doctor() {
  local plat name kind check branch category pf notes out missing=0
  plat="$(platform)"
  echo "platform: $plat"
  while IFS="$TAB" read -r name kind check branch category pf notes; do
    case "$name" in ''|'#'*|name) continue ;; esac
    [ "$kind" = system ] || continue
    case "$pf" in any|"$plat") ;; *) continue ;; esac
    if out="$(run_guarded "$check")" && [ -n "$out" ]; then
      printf 'OK       %-14s %s\n' "$name" "$(printf '%s\n' "$out" | head -n 1)"
    elif out="$(run_guarded "$check")"; then
      printf 'OK       %-14s\n' "$name"
    else
      printf 'MISSING  %-14s %s\n' "$name" "$notes"
      missing=$((missing + 1))
    fi
  done < "$MANIFEST"
  [ "$missing" -eq 0 ] || echo "$missing missing (nothing is installed by this script)"
  return 0
}

cmd_pin() {
  [ $# -eq 2 ] || die "usage: pin <name> <sha>"
  [ -n "$(row_for "$1")" ] || die "unknown tool: $1"
  [ -d "$TOOLS/$1/.git" ] || die "$1 is not cloned; run update first"
  is_dirty "$1" && die "$1 has local changes"
  git -C "$TOOLS/$1" fetch --quiet >/dev/null 2>&1 || true
  git -C "$TOOLS/$1" checkout --quiet --detach "$2" || die "cannot check out $2 in $1"
  git -C "$TOOLS/$1" submodule update --init --recursive --quiet >/dev/null 2>&1 || true
  set_pinned "$1" pinned
  write_lock
  echo "$1: pinned at $(git -C "$TOOLS/$1" rev-parse --short HEAD)"
}

cmd_unpin() {
  [ $# -eq 1 ] || die "usage: unpin <name>"
  local row br
  row="$(row_for "$1")"
  [ -n "$row" ] || die "unknown tool: $1"
  [ -d "$TOOLS/$1/.git" ] || die "$1 is not cloned; run update first"
  br="$(printf '%s' "$row" | cut -f3)"
  set_pinned "$1" -
  git -C "$TOOLS/$1" checkout --quiet "$br" || die "cannot check out $br in $1"
  write_lock
  echo "$1: unpinned, on $br at $(git -C "$TOOLS/$1" rev-parse --short HEAD) (run update to fast-forward)"
}

cmd_list() {
  local name kind source branch category pf notes
  printf '%-18s %-7s %-8s %-13s %-8s %s\n' NAME KIND BRANCH CATEGORY PLATFORM SOURCE
  while IFS="$TAB" read -r name kind source branch category pf notes; do
    case "$name" in ''|'#'*|name) continue ;; esac
    printf '%-18s %-7s %-8s %-13s %-8s %s\n' "$name" "$kind" "$branch" "$category" "$pf" "$source"
  done < "$MANIFEST"
}

[ -f "$MANIFEST" ] || die "missing $MANIFEST"

CMD=update
if [ $# -gt 0 ]; then
  case "$1" in
    update|status|doctor|pin|unpin|list) CMD="$1"; shift ;;
    -h|--help) usage; exit 0 ;;
  esac
fi

ONLY=""
OFFLINE=0
POS=""
while [ $# -gt 0 ]; do
  case "$1" in
    --only) [ $# -ge 2 ] || die "--only needs a value"; ONLY="$2"; shift 2 ;;
    --only=*) ONLY="${1#--only=}"; shift ;;
    --offline) OFFLINE=1; shift ;;
    -h|--help) usage; exit 0 ;;
    -*) die "unknown option: $1" ;;
    *) POS="$POS $1"; shift ;;
  esac
done
export ONLY OFFLINE

# shellcheck disable=SC2086
set -- $POS
case "$CMD" in
  update) cmd_update ;;
  status) cmd_status ;;
  doctor) cmd_doctor ;;
  pin) cmd_pin "$@" ;;
  unpin) cmd_unpin "$@" ;;
  list) cmd_list ;;
esac
